// Reads replica/design/tokens.json and writes:
//   src/styles/tokens.css       custom properties, light, dark, and the wall display scale
//   tailwind.preset.cjs         maps the roles into Tailwind 3.4 (chosen over 4: v4 needs Safari 16.4+)
//   replica/design/checks/{light,dark}.json   flat colour files for contrast.py
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveMarker } from '../src/lib/marker-core.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const designDir = path.resolve(app, '../replica/design');
const t = JSON.parse(fs.readFileSync(path.join(designDir, 'tokens.json'), 'utf8'));
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;

const markerNames = Object.keys(t.markers).filter((k) => !k.startsWith('_'));
const markers = { light: {}, dark: {} };
for (const th of ['light', 'dark']) for (const n of markerNames) markers[th][n] = deriveMarker(t.markers[n], th);

const roles = Object.keys(t.color);
const vars = (set, mk, shadow) => {
  const lines = roles.map((r) => `  --color-${r}: ${set[r]};`);
  for (const n of markerNames) lines.push(`  --marker-${n}-solid: ${mk[n].solid};`, `  --marker-${n}-on: ${mk[n].on};`, `  --marker-${n}-tint: ${mk[n].tint};`);
  lines.push(`  --shadow-lift: ${shadow.lift};`, `  --shadow-pop: ${shadow.pop};`);
  return lines.join('\n');
};

let css = `/* Generated by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit. */\n`;
css += `:root {\n${vars(t.color, markers.light, t.shadow)}\n`;
css += `  --font-body: ${t.font.body};\n  --font-display: ${t.font.display};\n`;
for (const [k, v] of Object.entries(t.type)) if (!k.startsWith('_')) css += `  --text-${k}: ${rem(v.size)};\n  --leading-${k}: ${rem(v.line)};\n  --weight-${k}: ${v.weight};\n`;
Object.entries(t.radius).forEach(([k, v]) => { css += `  --radius-${k}: ${v === 999 ? '999px' : rem(v)};\n`; });
Object.entries(t.motion).forEach(([k, v]) => { css += `  --motion-${k}: ${v};\n`; });
css += `  --target-min: ${t.target.min}rem;\n  --target-primary: ${t.target.primary}rem;\n  color-scheme: light;\n}\n`;
const dark = `${vars(t.dark, markers.dark, t.shadow_dark)}\n  color-scheme: dark;`;
css += `:root[data-theme="dark"] {\n${dark}\n}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${dark.replace(/^/gm, '  ')}\n  }\n}\n`;
css += `/* Wall display: everything is rem, so one root size scales the whole interface. */\n:root[data-surface="wall"] { font-size: 125%; }\n`;
css += `/* Person colour on any element: <div data-marker="tomato"> or style="--m-solid:...;--m-on:...;--m-tint:..." */\n`;
css += `[data-marker] { --m-solid: var(--marker-graphite-solid); --m-on: var(--marker-graphite-on); --m-tint: var(--marker-graphite-tint); }\n`;
for (const n of markerNames) css += `[data-marker="${n}"] { --m-solid: var(--marker-${n}-solid); --m-on: var(--marker-${n}-on); --m-tint: var(--marker-${n}-tint); }\n`;
css += `/* Custom (non-preset) person colours: the app sets --ml-* and --md-* from deriveMarker() for both themes. */\n`;
const cm = (p) => `--m-solid: var(--${p}-solid); --m-on: var(--${p}-on); --m-tint: var(--${p}-tint);`;
css += `[data-marker-custom] { ${cm('ml')} }\n:root[data-theme="dark"] [data-marker-custom] { ${cm('md')} }\n@media (prefers-color-scheme: dark) { :root:not([data-theme]) [data-marker-custom] { ${cm('md')} } }\n`;
fs.writeFileSync(path.join(app, 'src/lib/markers.generated.ts'), `// Generated by scripts/build-tokens.mjs. Do not edit.\nexport const MARKER_PRESETS = ${JSON.stringify(Object.fromEntries(markerNames.map((n) => [n, t.markers[n].toUpperCase()])), null, 2)} as const;\nexport type MarkerName = keyof typeof MARKER_PRESETS;\n`);
css += `@media (prefers-reduced-motion: reduce) {\n  :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }\n}\n`;
fs.writeFileSync(path.join(app, 'src/styles/tokens.css'), css);

// Tailwind 3.4 preset. Class names: bg-surface text-ink text-muted border-line, bg-m-tint border-m-solid text-m-on.
const v = (r) => `var(--color-${r})`;
const preset = {
  theme: {
    screens: Object.fromEntries(Object.entries(t.layout.breakpoints).map(([k, px]) => [k, `${px}px`])),
    colors: {
      transparent: 'transparent', current: 'currentColor',
      bg: v('bg'), surface: v('surface'), line: v('border'), 'line-input': v('border-input'),
      ink: v('text'), muted: v('text-muted'),
      accent: { DEFAULT: v('accent'), on: v('on-accent'), tint: v('accent-tint') },
      focus: v('focus'),
      danger: { DEFAULT: v('danger'), on: v('on-danger'), tint: v('danger-tint') },
      success: { DEFAULT: v('success'), tint: v('success-tint') },
      warning: { DEFAULT: v('warning'), tint: v('warning-tint') },
      scrim: v('scrim'),
      m: { solid: 'var(--m-solid)', on: 'var(--m-on)', tint: 'var(--m-tint)' },
    },
    fontFamily: { body: ['var(--font-body)'], display: ['var(--font-display)'] },
    fontSize: Object.fromEntries(Object.entries(t.type).filter(([k]) => !k.startsWith('_')).map(([k]) => [k, [`var(--text-${k})`, { lineHeight: `var(--leading-${k})`, fontWeight: `var(--weight-${k})` }]])),
    borderRadius: { none: '0', sm: 'var(--radius-sm)', md: 'var(--radius-md)', lg: 'var(--radius-lg)', pill: 'var(--radius-pill)', full: '9999px' },
    boxShadow: { lift: 'var(--shadow-lift)', pop: 'var(--shadow-pop)', none: 'none' },
    extend: {
      minHeight: { target: 'var(--target-min)', primary: 'var(--target-primary)' },
      minWidth: { target: 'var(--target-min)', primary: 'var(--target-primary)' },
      transitionDuration: { fast: 'var(--motion-fast)', base: 'var(--motion-base)', slow: 'var(--motion-slow)' },
      transitionTimingFunction: { soft: t.motion.ease },
    },
  },
};
fs.writeFileSync(path.join(app, 'tailwind.preset.cjs'), `// Generated by scripts/build-tokens.mjs. Do not edit.\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`);

// Flat files for contrast.py
fs.mkdirSync(path.join(designDir, 'checks'), { recursive: true });
for (const th of ['light', 'dark']) {
  const set = th === 'light' ? t.color : t.dark;
  const color = { ...set };
  const pairs = t.pairs.map((p) => [...p]);
  for (const n of markerNames) {
    const m = markers[th][n];
    color[`m-${n}-solid`] = m.solid; color[`m-${n}-on`] = m.on; color[`m-${n}-tint`] = m.tint;
    pairs.push([`m-${n}-on`, `m-${n}-solid`], ['text', `m-${n}-tint`], [`m-${n}-solid`, 'bg', 'ui'], [`m-${n}-solid`, 'surface', 'ui'], [`m-${n}-solid`, `m-${n}-tint`, 'ui'], ['focus', `m-${n}-tint`, 'ui']);
  }
  fs.writeFileSync(path.join(designDir, 'checks', `${th}.json`), JSON.stringify({ _about: `Generated from tokens.json for the ${th} theme. Do not edit.`, color, pairs }, null, 1));
}
console.log('tokens built:', roles.length, 'roles,', markerNames.length, 'markers x 2 themes');
